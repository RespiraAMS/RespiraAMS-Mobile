/// Spacing scale (4px system). Source: RESPIRAAMS_DESIGN_SYSTEM.md · 04/06.
abstract final class Spacing {
  /// Inline: icon–icon, pill–pill, dot–text.
  static const double inline = 8;

  /// Control: label–input, icon container–copy.
  static const double control = 12;

  /// Group: items of the same group, card within a section.
  static const double group = 16;

  /// Block: content–action, summary–section header.
  static const double block = 20;

  /// Section: between large blocks.
  static const double section = 24;

  /// Screen: hero, onboarding, large rest.
  static const double screen = 32;

  static const double xxxs = 4;
  static const double xxs = 8;
  static const double xs = 12;
  static const double sm = 16;
  static const double md = 20;
  static const double lg = 24;
  static const double xl = 32;
  static const double xxl = 40;
}
